// Sort phrases from longest to shortest to avoid partial replacements
export const SORTED_VI_KEYS = Object.keys(VI_TO_EN_DICTIONARY).sort((a, b) => b.length - a.length);

/**
 * High-performance string translator
 */
export function translateVietnameseString(input: string): string {
  if (!input || typeof input !== 'string') return input;
  // If no Vietnamese diacritics, return original text
  if (!/[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i.test(input)) {
    return input;
  }

  const trimmed = input.trim();
  if (VI_TO_EN_DICTIONARY[trimmed]) {
    return input.replace(trimmed, VI_TO_EN_DICTIONARY[trimmed]);
  }

  let result = input;
  for (const viKey of SORTED_VI_KEYS) {
    if (result.includes(viKey)) {
      if (viKey.length <= 6 && result.length > 35 && !result.includes(' ' + viKey + ' ')) {
        continue;
      }
      result = result.split(viKey).join(VI_TO_EN_DICTIONARY[viKey]);
      if (!/[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i.test(result)) {
        break;
      }
    }
  }
  return result;
}

const VI_CHAR_REGEX = /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i;
const IGNORED_TAGS = new Set(['SCRIPT', 'STYLE', 'CODE', 'PRE']);

interface TranslatedNode extends Text {
  __motorent_vi?: string;
  __motorent_en?: string;
}

interface TranslatedElement extends HTMLElement {
  __motorent_ph_vi?: string;
  __motorent_title_vi?: string;
  __motorent_aria_vi?: string;
}

function processTextNode(node: TranslatedNode, isEnglish: boolean) {
  if (isEnglish) {
    const current = node.nodeValue || '';
    if (node.__motorent_en && current === node.__motorent_en) return;

    if (VI_CHAR_REGEX.test(current)) {
      if (!node.__motorent_vi) {
        node.__motorent_vi = current;
      }
      const translated = translateVietnameseString(current);
      node.__motorent_en = translated;
      node.nodeValue = translated;
    }
  } else {
    if (node.__motorent_vi) {
      node.nodeValue = node.__motorent_vi;
      delete node.__motorent_vi;
      delete node.__motorent_en;
    }
  }
}

function processElementAttributes(el: TranslatedElement, isEnglish: boolean) {
  const tagName = el.tagName;
  if (IGNORED_TAGS.has(tagName)) return;

  // Placeholder
  const ph = el.getAttribute('placeholder');
  if (isEnglish) {
    if (ph && VI_CHAR_REGEX.test(ph)) {
      if (!el.__motorent_ph_vi) el.__motorent_ph_vi = ph;
      el.setAttribute('placeholder', translateVietnameseString(ph));
    }
  } else if (el.__motorent_ph_vi) {
    el.setAttribute('placeholder', el.__motorent_ph_vi);
    delete el.__motorent_ph_vi;
  }

  // Title
  const title = el.getAttribute('title');
  if (isEnglish) {
    if (title && VI_CHAR_REGEX.test(title)) {
      if (!el.__motorent_title_vi) el.__motorent_title_vi = title;
      el.setAttribute('title', translateVietnameseString(title));
    }
  } else if (el.__motorent_title_vi) {
    el.setAttribute('title', el.__motorent_title_vi);
    delete el.__motorent_title_vi;
  }

  // Aria-label
  const aria = el.getAttribute('aria-label');
  if (isEnglish) {
    if (aria && VI_CHAR_REGEX.test(aria)) {
      if (!el.__motorent_aria_vi) el.__motorent_aria_vi = aria;
      el.setAttribute('aria-label', translateVietnameseString(aria));
    }
  } else if (el.__motorent_aria_vi) {
    el.setAttribute('aria-label', el.__motorent_aria_vi);
    delete el.__motorent_aria_vi;
  }
}

/**
 * Walks and translates the DOM tree
 */
export function translateDomTree(root: Node, isEnglish: boolean) {
  if (!root || typeof window === 'undefined') return;

  // Walk text nodes
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (n) => {
      const parent = n.parentElement;
      if (!parent || IGNORED_TAGS.has(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  let currentNode = walker.nextNode();
  while (currentNode) {
    processTextNode(currentNode as TranslatedNode, isEnglish);
    currentNode = walker.nextNode();
  }

  // Walk element attributes
  if (root instanceof HTMLElement) {
    processElementAttributes(root as TranslatedElement, isEnglish);
    const elements = root.querySelectorAll<HTMLElement>('[placeholder], [title], [aria-label]');
    elements.forEach((el) => processElementAttributes(el as TranslatedElement, isEnglish));
  }
}

